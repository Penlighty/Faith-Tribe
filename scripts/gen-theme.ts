import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { interpolate, formatHex } from 'culori';
import { GAME_VISUALS } from '../src/design/icons/games';
import { TRIBES } from '../src/design/tribes/tribes';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const LIGHT_SURFACE = '#F4F1E6';
const DARK_SURFACE = '#121A15';

function mixColors(color1: string, color2: string, ratio: number): string {
  const mixer = interpolate([color1, color2], 'rgb');
  const result = mixer(ratio);
  return formatHex(result) || color1;
}

export function generateThemesCss(): string {
  let css = `/**
 * Generated by scripts/gen-theme.ts. Do not edit by hand.
 * Game and Tribe Scope Design Tokens (Light, Dark, and Media Preferences)
 */\n\n`;

  css += `/* ==========================================================================\n`;
  css += `   GAME SCOPE TOKENS (--game-container, --game-ink, --game-surface, --game-on-surface)\n`;
  css += `   ========================================================================== */\n\n`;

  const gameIds = Object.keys(GAME_VISUALS) as (keyof typeof GAME_VISUALS)[];

  for (const gameId of gameIds) {
    const visual = GAME_VISUALS[gameId];
    const lightSurface = mixColors(LIGHT_SURFACE, visual.container, 0.35);
    const darkSurface = mixColors(DARK_SURFACE, visual.ink, 0.30);

    const selector = gameId === 'who-said-that'
      ? `[data-game="who-said-that"], [data-game="who-said"]`
      : `[data-game="${gameId}"]`;

    const darkSelector = gameId === 'who-said-that'
      ? `[data-theme="dark"] [data-game="who-said-that"], [data-theme="dark"][data-game="who-said-that"], .dark [data-game="who-said-that"], .dark[data-game="who-said-that"], [data-theme="dark"] [data-game="who-said"], [data-theme="dark"][data-game="who-said"], .dark [data-game="who-said"], .dark[data-game="who-said"]`
      : `[data-theme="dark"] [data-game="${gameId}"], [data-theme="dark"][data-game="${gameId}"], .dark [data-game="${gameId}"], .dark[data-game="${gameId}"]`;

    const mediaDarkSelector = gameId === 'who-said-that'
      ? `:root:not([data-theme="light"]):not(.light) [data-game="who-said-that"], :root:not([data-theme="light"]):not(.light)[data-game="who-said-that"], :root:not([data-theme="light"]):not(.light) [data-game="who-said"], :root:not([data-theme="light"]):not(.light)[data-game="who-said"]`
      : `:root:not([data-theme="light"]):not(.light) [data-game="${gameId}"], :root:not([data-theme="light"]):not(.light)[data-game="${gameId}"]`;

    // Light
    css += `/* Game: ${visual.name} (Light) */\n`;
    css += `${selector} {\n`;
    css += `  --game-container: ${visual.container};\n`;
    css += `  --game-ink: ${visual.ink};\n`;
    css += `  --game-surface: ${lightSurface};\n`;
    css += `  --game-on-surface: ${visual.ink};\n`;
    css += `}\n\n`;

    // Dark explicit
    css += `/* Game: ${visual.name} (Dark) */\n`;
    css += `${darkSelector} {\n`;
    css += `  --game-container: ${visual.ink};\n`;
    css += `  --game-ink: ${visual.container};\n`;
    css += `  --game-surface: ${darkSurface};\n`;
    css += `  --game-on-surface: ${visual.container};\n`;
    css += `}\n\n`;

    // Dark prefers-color-scheme
    css += `@media (prefers-color-scheme: dark) {\n`;
    css += `  ${mediaDarkSelector} {\n`;
    css += `    --game-container: ${visual.ink};\n`;
    css += `    --game-ink: ${visual.container};\n`;
    css += `    --game-surface: ${darkSurface};\n`;
    css += `    --game-on-surface: ${visual.container};\n`;
    css += `  }\n`;
    css += `}\n\n`;
  }

  css += `/* ==========================================================================\n`;
  css += `   TRIBE SCOPE TOKENS (--tribe-container, --tribe-ink)\n`;
  css += `   ========================================================================== */\n\n`;

  for (const tribe of TRIBES) {
    css += `/* Tribe: ${tribe.name} (${tribe.source}) */\n`;
    css += `[data-tribe="${tribe.id}"] {\n`;
    css += `  --tribe-container: ${tribe.container};\n`;
    css += `  --tribe-ink: ${tribe.ink};\n`;
    css += `}\n\n`;
  }

  return css;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const css = generateThemesCss();
  const outputPath = path.resolve(__dirname, '../src/design/tokens/themes.generated.css');
  fs.writeFileSync(outputPath, css, 'utf-8');
  console.log(`[gen-theme] Successfully wrote ${outputPath}`);
}
