import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { svgPathProperties } from 'svg-path-properties';
import { GAME_VISUALS, GameId } from '../src/design/icons/games';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

export interface Point {
  x: number;
  y: number;
}

export interface ShapeDefinition {
  points: [number, number][];
  clipPath: string;
}

function calculateSignedArea(points: Point[]): number {
  let area = 0;
  for (let i = 0; i < points.length; i++) {
    const j = (i + 1) % points.length;
    area += points[i].x * points[j].y - points[j].x * points[i].y;
  }
  return area / 2;
}

export function sampleShape(pathString: string, numPoints = 96): [number, number][] {
  const properties = new svgPathProperties(pathString);
  const totalLength = properties.getTotalLength();
  const step = totalLength / numPoints;

  const rawPoints: Point[] = [];
  for (let i = 0; i < numPoints; i++) {
    const distance = i * step;
    const pt = properties.getPointAtLength(distance);
    rawPoints.push({ x: pt.x, y: pt.y });
  }

  // Find top-most point (lowest y in screen coords)
  let topIndex = 0;
  let minY = Infinity;
  for (let i = 0; i < rawPoints.length; i++) {
    if (rawPoints[i].y < minY || (rawPoints[i].y === minY && rawPoints[i].x < rawPoints[topIndex].x)) {
      minY = rawPoints[i].y;
      topIndex = i;
    }
  }

  // Rotate points so top-most point is at index 0
  let reordered: Point[] = [
    ...rawPoints.slice(topIndex),
    ...rawPoints.slice(0, topIndex)
  ];

  // In screen coords (y down), a positive signed area means clockwise winding
  const signedArea = calculateSignedArea(reordered);
  if (signedArea < 0) {
    // Reverse points to ensure clockwise winding, keeping top-most point at index 0
    const first = reordered[0];
    const rest = reordered.slice(1).reverse();
    reordered = [first, ...rest];
  }

  // Normalize/clamp coordinates strictly to [0, 100] with 2 decimal precision
  return reordered.map((pt) => {
    const clampedX = Math.max(0, Math.min(100, Math.round(pt.x * 100) / 100));
    const clampedY = Math.max(0, Math.min(100, Math.round(pt.y * 100) / 100));
    return [clampedX, clampedY];
  });
}

export function generateShapesCode(): string {
  const gameIds = Object.keys(GAME_VISUALS) as GameId[];
  const shapes: Record<string, ShapeDefinition> = {};

  for (const id of gameIds) {
    const visual = GAME_VISUALS[id];
    const points = sampleShape(visual.shapePath, 96);
    const clipPolygon = `polygon(${points.map(([x, y]) => `${x}% ${y}%`).join(', ')})`;
    shapes[id] = {
      points,
      clipPath: clipPolygon
    };
  }

  let code = `// Generated by scripts/gen-shapes.ts. Do not edit by hand.\n`;
  code += `// 96-point normalized polygon clips and coordinate arrays for all 8 game silhouettes\n\n`;
  code += `export interface ShapeDefinition {\n`;
  code += `  points: [number, number][];\n`;
  code += `  clipPath: string;\n`;
  code += `}\n\n`;
  code += `export const GAME_SHAPES: Record<string, ShapeDefinition> = ${JSON.stringify(shapes, null, 2)};\n\n`;
  code += `export type ShapeGameId = keyof typeof GAME_SHAPES;\n`;

  return code;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const code = generateShapesCode();
  const dirPath = path.resolve(__dirname, '../src/design/shapes');
  if (!fs.existsSync(dirPath)) {
    fs.mkdirSync(dirPath, { recursive: true });
  }
  const outputPath = path.resolve(dirPath, 'shapes.generated.ts');
  fs.writeFileSync(outputPath, code, 'utf-8');
  console.log(`[gen-shapes] Successfully wrote ${outputPath}`);
}
